/* =========================================================
   FILTERING AND SORTING
========================================================= */

function applyFiltersAndSort() {
    const searchTerm =
        search
            ? search.value.trim().toLowerCase()
            : "";

    const selectedStatus =
        statusFilter
            ? statusFilter.value
            : "All";

    const selectedDueDate =
        dueDateFilter
            ? dueDateFilter.value
            : "All";

    const selectedSort =
        sortFilter
            ? sortFilter.value
            : "Priority";

    const today =
        getLocalDateString();

    const sevenDaysFromNow =
        new Date();

    sevenDaysFromNow.setDate(
        sevenDaysFromNow.getDate() + 7
    );

    const nextSevenDays =
        getLocalDateString(sevenDaysFromNow);

    let filteredOrders =
        orders.filter(function (order) {
            const customer =
                String(order.customer || "")
                    .toLowerCase();

            const item =
                String(order.item || "")
                    .toLowerCase();

            const contact =
                String(order.contact || "")
                    .toLowerCase();

            const orderId =
                String(order.id || "")
                    .toLowerCase();

            const color =
                String(order.color || "")
                    .toLowerCase();

            const notes =
                String(order.notes || "")
                    .toLowerCase();

            const matchesSearch =
                customer.includes(searchTerm) ||
                item.includes(searchTerm) ||
                contact.includes(searchTerm) ||
                orderId.includes(searchTerm) ||
                color.includes(searchTerm) ||
                notes.includes(searchTerm);

            const matchesStatus =
                selectedStatus === "All" ||
                order.status === selectedStatus;

            let matchesDueDate = true;

            if (selectedDueDate === "Overdue") {
                matchesDueDate =
                    Boolean(order.dueDate) &&
                    order.dueDate < today &&
                    order.status !== "Delivered";
            }

            if (selectedDueDate === "Today") {
                matchesDueDate =
                    order.dueDate === today;
            }

            if (selectedDueDate === "Next7Days") {
                matchesDueDate =
                    Boolean(order.dueDate) &&
                    order.dueDate >= today &&
                    order.dueDate <= nextSevenDays;
            }

            if (selectedDueDate === "Future") {
                matchesDueDate =
                    Boolean(order.dueDate) &&
                    order.dueDate > nextSevenDays;
            }

            return (
                matchesSearch &&
                matchesStatus &&
                matchesDueDate
            );
        });

    filteredOrders.sort(function (orderA, orderB) {
        /*
            When all statuses are displayed, Delivered
            orders remain at the bottom regardless of
            the selected sorting option.
        */

        if (selectedStatus === "All") {
            const orderAIsDelivered =
                orderA.status === "Delivered";

            const orderBIsDelivered =
                orderB.status === "Delivered";

            if (
                orderAIsDelivered &&
                !orderBIsDelivered
            ) {
                return 1;
            }

            if (
                !orderAIsDelivered &&
                orderBIsDelivered
            ) {
                return -1;
            }
        }

        if (selectedSort === "Newest") {
            return (
                getCreatedTime(orderB) -
                getCreatedTime(orderA)
            );
        }

        if (selectedSort === "DueSoon") {
            const dueDateDifference =
                getDueDateValue(orderA) -
                getDueDateValue(orderB);

            if (dueDateDifference !== 0) {
                return dueDateDifference;
            }

            return (
                getCreatedTime(orderB) -
                getCreatedTime(orderA)
            );
        }

        if (selectedSort === "DueLate") {
            const dueDateDifference =
                getDueDateValue(orderB) -
                getDueDateValue(orderA);

            if (dueDateDifference !== 0) {
                return dueDateDifference;
            }

            return (
                getCreatedTime(orderB) -
                getCreatedTime(orderA)
            );
        }

        /*
            Default priority:

            1. Pending
            2. Printing
            3. Ready
            4. Delivered
        */

        const statusDifference =
            getStatusPriority(orderA.status) -
            getStatusPriority(orderB.status);

        if (statusDifference !== 0) {
            return statusDifference;
        }

        /*
            Orders with the same status are arranged
            newest first.
        */

        return (
            getCreatedTime(orderB) -
            getCreatedTime(orderA)
        );
    });

    renderOrders(filteredOrders);
}


