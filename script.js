/* =========================================================
   EDIT ORDER
========================================================= */

function editOrder(firestoreId) {
    const order =
        orders.find(function (currentOrder) {
            return (
                currentOrder.firestoreId ===
                firestoreId
            );
        });

    if (!order) {
        alert("Order not found.");
        return;
    }

    editingFirestoreId =
        order.firestoreId;

    setValue(
        "customer",
        order.customer
    );

    setValue(
        "contact",
        order.contact
    );

    setValue(
        "item",
        order.item
    );

    setValue(
        "qty",
        order.qty
    );

    setValue(
        "color",
        order.color
    );

    setValue(
        "dueDate",
        order.dueDate
    );

    /*
        The price input should show unit price,
        not the total order price.
    */

    setValue(
        "price",
        getOrderUnitPrice(order)
    );

    setValue(
        "status",
        order.status
    );

    setValue(
        "notes",
        order.notes
    );

    if (submitButton) {
        submitButton.innerText =
            "Update Order";
    }

    if (form) {
        form.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    }
}


/* =========================================================
   DELETE ORDER
========================================================= */

async function deleteOrder(firestoreId) {
    const order =
        orders.find(function (currentOrder) {
            return (
                currentOrder.firestoreId ===
                firestoreId
            );
        });

    if (!order) {
        alert("Order not found.");
        return;
    }

    const customerName =
        order.customer || "this customer";

    const confirmed =
        confirm(
            `Delete the order for ${customerName}?`
        );

    if (!confirmed) {
        return;
    }

    try {
        await deleteDoc(
            doc(
                db,
                "orders",
                firestoreId
            )
        );

        if (
            editingFirestoreId === firestoreId
        ) {
            resetOrderForm();
        }
    } catch (error) {
        console.error(
            "Error deleting order:",
            error
        );

        alert(
            "The order could not be deleted. Please check the internet connection and Firestore permissions."
        );
    }
}


/* =========================================================
   DASHBOARD TOTALS
========================================================= */

function updateDashboard() {
    const totalOrdersElement =
        document.getElementById("totalOrders");

    const pendingOrdersElement =
        document.getElementById("pendingOrders");

    const completedOrdersElement =
        document.getElementById("completedOrders");

    const totalSalesElement =
        document.getElementById("totalSales");

    if (totalOrdersElement) {
        totalOrdersElement.innerText =
            orders.length;
    }

    if (pendingOrdersElement) {
        /*
            Pending dashboard card counts all orders
            that are not yet Delivered.
        */

        pendingOrdersElement.innerText =
            orders.filter(function (order) {
                return (
                    order.status !== "Delivered"
                );
            }).length;
    }

    if (completedOrdersElement) {
        completedOrdersElement.innerText =
            orders.filter(function (order) {
                return (
                    order.status === "Delivered"
                );
            }).length;
    }

    if (totalSalesElement) {
        const totalSales =
            orders.reduce(
                function (sum, order) {
                    return (
                        sum +
                        getOrderTotalPrice(order)
                    );
                },
                0
            );

        totalSalesElement.innerText =
            formatMoney(totalSales);
    }
}


