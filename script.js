/* =========================================================
   RENDER ORDERS
========================================================= */

function renderOrders(filteredOrders = orders) {
    if (!table) {
        return;
    }

    table.innerHTML = "";

    if (filteredOrders.length === 0) {
        table.innerHTML = `
            <tr>
                <td colspan="13"
                    style="
                        text-align: center;
                        padding: 30px;
                        color: #888;
                    "
                >
                    No orders found.
                </td>
            </tr>
        `;

        return;
    }

    filteredOrders.forEach(function (order) {
        const statusClass =
            getStatusClass(order.status);

        const dueDateClass =
            getDueDateClass(order);

        const unitPrice =
            getOrderUnitPrice(order);

        const totalPrice =
            getOrderTotalPrice(order);

        const orderId =
            escapeHTML(order.id || "");

        const customer =
            escapeHTML(order.customer);

        const contact =
            escapeHTML(order.contact);

        const item =
            escapeHTML(order.item);

        const quantity =
            escapeHTML(order.qty);

        const color =
            escapeHTML(order.color);

        const dueDate =
            escapeHTML(order.dueDate || "No due date");

        const status =
            escapeHTML(order.status || "Pending");

        const notes =
            escapeHTML(order.notes || "");

        const firestoreId =
            escapeHTML(order.firestoreId);

        table.innerHTML += `
            <tr>
                <td>${orderId}</td>

                <td>${customer}</td>

                <td>${contact}</td>

                <td>${item}</td>

                <td>${quantity}</td>

                <td>${color}</td>

                <td class="${dueDateClass}">
                    ${dueDate}
                </td>

                <td>
                    ₱${formatMoney(unitPrice)}
                </td>

                <td>
                    ₱${formatMoney(totalPrice)}
                </td>

                <td>
                    <span class="status-badge ${statusClass}">
                        ${status}
                    </span>
                </td>

                <td>${notes}</td>

                <td>
                    <button
                        type="button"
                        class="actionBtn edit"
                        data-action="edit"
                        data-id="${firestoreId}"
                    >
                        Edit
                    </button>

                    <button
                        type="button"
                        class="actionBtn delete"
                        data-action="delete"
                        data-id="${firestoreId}"
                    >
                        Delete
                    </button>
                </td>
            </tr>
        `;
    });
}


